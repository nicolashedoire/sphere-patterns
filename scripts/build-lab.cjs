'use strict';

const fs = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '..');
const work = path.join(repo, 'work');
const sources = new Map(fs.readdirSync(work)
  .filter(name => /\.(?:c?js|json)$/u.test(name))
  .map(name => [name, fs.readFileSync(path.join(work, name), 'utf8')]));

function findSource(description, test) {
  const files = [...sources].filter(([, source]) => test(source));
  if (files.length !== 1) throw new Error('Expected one ' + description + ', found ' + files.length);
  return files[0];
}

function section(source, first, next) {
  const start = source.indexOf(first);
  const end = source.indexOf(next, start + 1);
  if (start === -1 || end === -1) throw new Error('Missing simulation source boundaries.');
  return source.slice(start, end);
}

function sourceRequire(source, binding) {
  const lines = source.split('\n').filter(line => line.startsWith(binding) && line.includes('require('));
  if (lines.length !== 1) throw new Error('Cannot find source dependency ' + binding);
  return lines[0];
}

const [roundtripName, roundtrip] = findSource('round-trip simulation',
  source => source.includes('class FileSimulation extends SeparatedLanes'));
const [alignmentName, alignment] = findSource('alignment circuit',
  source => source.includes('class AlignmentCircuit {'));
const [, probeData] = findSource('distant-probe configuration', source => {
  if (!source.startsWith('{"nodes":[')) return false;
  const value = JSON.parse(source);
  return Array.isArray(value.nodes) && Array.isArray(value.ports);
});

const nodeAssert = `module.exports = {
  ok(value, message) { if (!value) throw new Error(message || 'Simulation invariant failed.'); },
  equal(actual, expected) { if (actual !== expected) throw new Error('Unexpected simulation value.'); }
};`;
const networkRequire = sourceRequire(roundtrip, 'const { createNetwork }');
const laneRequire = sourceRequire(roundtrip, 'const { Simulation: SeparatedLanes }');
const roundtripCore = [
  "const assert = require('node:assert/strict');",
  networkRequire,
  laneRequire,
  section(roundtrip, 'const SEED =', 'function beginRecording')
    .replace(/^  const farBand = .*;$/mu, '  const farBand = ' + probeData.trim() + ';'),
  'module.exports = { createNetwork, FileSimulation, createSetup };'
].join('\n');
const alignmentCore = [
  'const { createSetup } = require(' + JSON.stringify('./' + roundtripName) + ');',
  section(alignment, 'const SIZE =', 'class AutoAlignmentSimulation'),
  'module.exports = { AlignmentCircuit, setup, START, C_LEVEL };'
].join('\n');

const modules = new Map([['node:assert/strict', nodeAssert]]);
function bundle(name, source = sources.get(name)) {
  if (modules.has(name)) return;
  if (source === undefined) throw new Error('Cannot bundle ' + name);
  modules.set(name, source);
  for (const match of source.matchAll(/\brequire\(['"]\.\/([^'"]+)['"]\)/gu)) bundle(match[1]);
}
bundle(roundtripName, roundtripCore);
bundle(alignmentName, alignmentCore);

const definitions = [...modules].map(([name, source]) =>
  JSON.stringify(name) + ': function (module, exports, require) {\n' + source + '\n}');
const bundleSource = `// Generated by scripts/build-lab.cjs from the simulation sources in work/.
'use strict';
(() => {
  const definitions = {\n${definitions.join(',\n')}\n};
  const loaded = Object.create(null);
  function load(request) {
    const name = request.startsWith('./') ? request.slice(2) : request;
    if (loaded[name]) return loaded[name].exports;
    if (!Object.hasOwn(definitions, name)) throw new Error('Missing simulation module ' + name);
    const module = { exports: {} };
    loaded[name] = module;
    definitions[name](module, module.exports, load);
    return module.exports;
  }
  globalThis.SphereLab = Object.freeze({
    ...load(${JSON.stringify(roundtripName)}),
    ...load(${JSON.stringify(alignmentName)})
  });
})();
`;
const output = path.join(repo, 'lab', 'engine.js');
fs.writeFileSync(output, bundleSource);
console.log('Built lab/engine.js from ' + modules.size + ' modules.');
